CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(120) NOT NULL, author VARCHAR(100) NOT NULL,
 category VARCHAR(30) NOT NULL, description VARCHAR(1500) NOT NULL,
 price INT NOT NULL CHECK(price > 0), stock INT NOT NULL CHECK(stock >= 0),
 color VARCHAR(20) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS shop_orders (
 id VARCHAR(36) PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES accounts(id),
 request_key VARCHAR(80) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 total INT NOT NULL, shipping INT NOT NULL, status VARCHAR(30) NOT NULL,
 payment VARCHAR(30) NOT NULL, recipient VARCHAR(80) NOT NULL,
 address VARCHAR(300) NOT NULL, city VARCHAR(80) NOT NULL, postcode VARCHAR(10) NOT NULL,
 UNIQUE(account_id, request_key)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id VARCHAR(36) NOT NULL REFERENCES shop_orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 title VARCHAR(120) NOT NULL, quantity INT NOT NULL, price INT NOT NULL
);
